"""ADK-backed demo for conversation-level unified verification.

The ADK runtime generates the agent responses and execution traces. Journey
stage labels and quality scores remain scenario fixtures until the project has
a model-derived outcome scoring implementation.
"""

from __future__ import annotations

import argparse
import asyncio
import textwrap
from typing import Any

from workshop_verify_agents.demo_offline_verification import (
    _preview,
    _print_evidence,
    _print_table,
)
from workshop_verify_agents.examples.conversations import get_exchanges, get_scenario, list_scenarios
from workshop_verify_agents.journey.journey_taxonomy import stage_weight
from workshop_verify_agents.verification.offline_verifier import (
    verify_completed_conversation,
)
from workshop_verify_agents.verification.online_verifier import verify_turn_behaviour


async def _run_adk_scenario(
    scenario: dict[str, Any],
    conversation_id: str,
) -> tuple[list[dict[str, str]], list[Any]]:
    """Run scenario user turns through ADK and replace fixture agent responses.

    All turns share one event loop; per-turn asyncio.run() calls would bind
    litellm's background logging worker to a loop that no longer exists.
    """
    # Importing the ADK runner creates the OpenAI-backed model, so defer it
    # until this explicit ADK-only path is selected.
    from workshop_verify_agents.adk_runtime.runner import ADKConversationRunner

    runner = ADKConversationRunner()
    conversation_turns: list[dict[str, str]] = []
    behaviour_results = []
    pending_response: str | None = None

    for index, turn in enumerate(scenario.get("turns", [])):
        role = str(turn.get("role", "unknown"))
        text = str(turn.get("text", ""))

        if role == "user":
            response, _raw_events, trace = await runner.run_turn(text, conversation_id)
            pending_response = response
            conversation_turns.append({"role": role, "text": text})
            behaviour_results.append(
                verify_turn_behaviour(
                    conversation_id=conversation_id,
                    turn_index=index,
                    execution_trace=trace,
                )
            )
        elif role == "agent" and pending_response is not None:
            conversation_turns.append({"role": role, "text": pending_response})
            pending_response = None
        else:
            conversation_turns.append({"role": role, "text": text})

    return conversation_turns, behaviour_results


def demo_adk_verification(scenario_name: str = "mortgage_happy_path") -> None:
    """Run one fixture conversation with ADK-generated responses and traces.

    ``expected_stage_labels`` and ``mocked_quality_scores`` from the selected
    fixture are retained for journey-aware outcome verification. They are not
    generated by ADK or inferred from the actual responses.
    """
    asyncio.run(_demo_adk_verification_async(scenario_name))


async def _demo_adk_verification_async(scenario_name: str) -> None:
    scenario = get_scenario(scenario_name)
    conversation_id = f"adk::{scenario_name}"
    fixture_exchanges = get_exchanges(scenario)
    stages = [str(exchange["journey_stage"]) for exchange in fixture_exchanges]
    scores = [float(exchange["quality_score"]) for exchange in fixture_exchanges]

    try:
        conversation_turns, behaviour_results = await _run_adk_scenario(scenario, conversation_id)
    except OSError as exc:
        print(f"ADK demo unavailable: {exc}")
        print("Set OPENAI_API_KEY in your .env file.")
        return

    adk_exchanges = []
    for index, exchange in enumerate(fixture_exchanges):
        user_turn_index = index * 2
        agent_turn_index = user_turn_index + 1
        adk_exchanges.append({
            **exchange,
            "user_message": conversation_turns[user_turn_index]["text"],
            "agent_response": conversation_turns[agent_turn_index]["text"],
        })

    unified = verify_completed_conversation(
        conversation_id=conversation_id,
        behaviour_results=behaviour_results,
        conversation_turns=conversation_turns,
        turn_scores=scores,
        journey_stage_labels=stages,
        conversation_exchanges=adk_exchanges,
    )

    print(f"Scenario: {scenario_name}")
    print("Runtime: ADK-generated agent responses and normalized execution traces")
    print("Outcome inputs: fixture journey-stage labels and mocked quality scores")

    turn_rows = []
    for index, exchange in enumerate(adk_exchanges):
        stage = exchange["journey_stage"]
        score = exchange["quality_score"]
        weight = stage_weight(stage) if stage != "unknown" else "n/a"
        turn_rows.append([
            index,
            "exchange",
            _preview(exchange["agent_response"]),
            stage,
            f"{float(score):.2f}" if isinstance(score, (int, float)) else score,
            f"{float(weight):.2f}" if isinstance(weight, (int, float)) else weight,
        ])
    _print_table(
        "Conversation Turns",
        ["turn_index", "role", "text_preview", "journey_stage", "quality_score", "stage_weight"],
        turn_rows,
    )

    behaviour_rows = [
        [
            result.turn_index,
            len(result.execution_trace.events),
            len(result.business_signals),
            result.behaviour_assessment.overall_status.value,
        ]
        for result in behaviour_results
    ]
    _print_table(
        "Per-turn Behaviour Summary (ADK user turns)",
        ["fixture_turn_index", "trace_event_count", "signal_count", "behaviour_status"],
        behaviour_rows,
    )

    _print_evidence("Behaviour Evidence (conversation scope)", unified.behaviour_evidence_conversation_scope)
    _print_evidence(
        "Outcome Evidence (conversation scope)",
        unified.outcome_result.outcome_evidence if unified.outcome_result else [],
    )

    outcome_summary = unified.outcome_result.journey_aware_result if unified.outcome_result else {}
    if outcome_summary:
        print("\nConversation-level Outcome Summary")
        print(f"  - simple_average_score: {outcome_summary.get('simple_average', 'n/a')}")
        print(f"  - journey_weighted_score: {outcome_summary.get('journey_weighted_score', 'n/a')}")
        print(f"  - critical_stage_failures: {outcome_summary.get('critical_stage_failures', [])}")

    print("\nFinal Unified Assessment")
    print(f"  - completeness: {unified.completeness}")
    print(f"  - overall_status: {unified.final_assessment.overall_status.value}")
    if unified.final_assessment.summary:
        print(f"  - summary: {textwrap.shorten(unified.final_assessment.summary, width=180)}")
    for warning in unified.warnings:
        print(f"  - warning: {warning}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run scenario conversations through the ADK runtime.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--scenario", default=None, help="Registered scenario name to run.")
    group.add_argument("--all", action="store_true", help="Run every registered scenario.")
    args = parser.parse_args()

    names = list_scenarios() if args.all else [args.scenario or "mortgage_happy_path"]

    async def _run_all(scenario_names: list[str]) -> None:
        # Share one event loop across scenarios so litellm's background
        # logging worker is not rebound to a closed loop between runs.
        for scenario_name in scenario_names:
            await _demo_adk_verification_async(scenario_name)
            print("\n" + "=" * 80 + "\n")

    asyncio.run(_run_all(names))